#!/bin/sh
# 段(または 1 周)を走らせて、**出力を切らずに**ログへ追記する(#204 / T3)。
#
# ## なぜ要るか
#
# 件数の照合(tools/check_test_count_ratchet.py)は**ログの全文**を読む。
# `tail` や `grep` で切ると段を見落とす —— T1(#202)の点検で実際に起きた。
# だから「走らせる」と「ログへ落とす」を 1 箇所にまとめて、切る口を作らない。
#
# もう 1 つの仕事が**段の名乗り**である。`make test-qemu-all` は再帰呼び出しを
# echo するので段の名前がログから導出できるが、**CI は段ごとに別のコマンド**なので
# その echo が出ない。名乗りが無いと「どの段か」が分からず、
# 同じ台本をイメージを変えて 2 回走らせる段(partition の gpt/mbr など)を
# 区別できない。そこでこのスクリプトが `### STAGE <名前>` を頭に 1 行出す。
#
# ## 使い方
#
#   tools/qemu_stage_log.sh <ログ> <段の名前|-> <コマンド...>
#
#   <段の名前> が `-` のときは名乗りを出さない(1 周まるごとを包む場合。
#   make の再帰呼び出しの echo が段を名乗るので要らない)。
#
# ログは**追記**する。周の頭で消すのは呼び出し側の仕事である
# (CI は段ごとに別のコマンドなので、ここで消すと前の段が消える)。
#
# ## 終了状態
#
# **包んだコマンドの終了状態をそのまま返す。** `cmd | tee` だと tee の
# 終了状態になってしまい(/bin/sh に pipefail は無い)、**段の失敗が消える。**
# それを避けるため、終了状態を一時ファイル経由で持ち出している。

set -e

if [ "$#" -lt 3 ]; then
    echo "使い方: $0 <ログ> <段の名前|-> <コマンド...>" >&2
    exit 2
fi

LOG="$1"
STAGE="$2"
shift 2

mkdir -p "$(dirname "$LOG")"

if [ "$STAGE" != "-" ]; then
    printf '### STAGE %s\n' "$STAGE" | tee -a "$LOG"
fi

STATUS_FILE="$(mktemp)"
# **"$@" の終了状態を取り出す。** 書き先はファイルなのでログには出ない。
# `set +e` は要る: パイプの左は部分シェルなので、set -e のままだと
# コマンドが落ちた時点で部分シェルが終わり、**終了状態を書く行まで来ない**
# (最初に書いたときこれで空になり、状態が取れなかった)
{ set +e; "$@" 2>&1; echo $? > "$STATUS_FILE"; } | tee -a "$LOG"
ec="$(cat "$STATUS_FILE")"
rm -f "$STATUS_FILE"
# 状態が取れなかったときは失敗側に倒す(**取れないことを成功にしない**)
if [ -z "$ec" ]; then
    echo "ERROR: $0 が包んだコマンドの終了状態を取れなかった" >&2
    exit 1
fi
exit "$ec"
