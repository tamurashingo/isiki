#ifndef _LOAD_H_
#define _LOAD_H_

#include "types.h"
#include "stream.h"

/**
 * ストリームからS式を読めなくなるまで順に評価する「読んで評価する輪」。
 *
 * 9P経由のLOAD・マウント経由のLOAD(M2)・カーネルへ同梱したソースの
 * 読み込み(M1)で**共有する**。呼び出し元は開いたストリームを渡すだけでよい。
 * ストリームはこの関数が閉じる(正常終了・構文エラー・I/Oエラーのいずれでも)。
 *
 * **包まれたストリーム(MAGIC_STREAM)も渡せる。** その場合os_stream_t本体は
 * GCのたびに別アドレスへ複製されるので、この関数は**反復ごとに
 * self_handleから実体を取り直す**(M2-T0 / #196)。呼び出し元が渡した生ポインタは
 * 1回目のGCで古くなるため、**この関数から戻った後は使わないこと。**
 * 包まれていない(self_handleがnil)ストリーム、すなわち9p経由のcc_loadと
 * カーネル同梱の読み込みはCのローカル/静的領域にあってGCで動かないので、
 * 渡した生ポインタをそのまま使う。
 *
 * **打ち切りは失敗にならない。** エラーで打ち切られたフォームは理由を1行表示して
 * 飛ばし、次のフォームへ進む。最後まで読めれば打ち切りがあってもg_sym_tを返す。
 * したがって**戻り値だけでは「半分失敗した」が分からない**ので、
 * 止める判断をしたい呼び出し元はout_aborted_countを渡す。
 *
 * @param stream 読み込み元(開いた状態で渡す。この関数が閉じる)
 * @param name エラー表示に使う読み込み元の名前。**開く用途には使わない**
 *             (9P経由ならパスそのもの)
 * @param env 評価に使う環境(読んだ各S式もこのenvで評価される)
 * @param out_aborted_count 打ち切られたフォームの件数を**加算**する先。
 *        不要なら0を渡せる。**ただし総数(os_load_aborted_total)はこことは無関係に
 *        必ず数える**(#197)。以前はこの引数が0の呼び元では加算自体が起きず、
 *        「捨てられていた」のではなく**最初から数えられていなかった**
 * @return 最後まで読めればg_sym_t。構文エラー・I/Oエラーのときは
 *         os_signal_io_errorの戻り値(signalが上がるので通常は戻らない)
 */
lisp_val_t os_load_from_stream(os_stream_t *stream, const char *name, lisp_val_t env,
                               int *out_aborted_count);

/**
 * 組み込み関数LOAD。第一引数のパスを開いてos_load_from_streamへ渡す
 * (= 開き方だけを決める層)。
 *
 * **パスの契約(M2-T1 / #193)。先頭の区切りで経路が分かれる:**
 *   - **先頭が'/'でない** -> ホスト共有(9P)のエクスポートルートから見た相対パス。
 *     **マウント表は引かない**(従来どおりの挙動)
 *   - **先頭が'/'** -> os_mount_resolveでマウント表を引く。"/9p"配下は
 *     *mounts*に登録が無くても常にホスト共有へ解決される(mount.c)。
 *     FATへ解決された場合はファイル全体を一括で読み、
 *     **言語側の値(MAGIC_STREAM)に包んで**os_load_from_streamへ渡す
 *     (包まないとGCで中身ごと消える。os_load_from_streamの注記を参照)
 *   - **どのマウントにも解決できなければ"no such mount"でsignalする。
 *     ホスト共有へ落とさない**
 *
 * **心覚え: 相対 = 母艦(開発時)、絶対 = 機械の中。**
 * 相対をホスト共有に残すのは、いまloadへ渡っている名前がほぼ全部
 * 「先頭に区切りが無い相対指定」で、マウント表は絶対パス前提だからである
 * (素直に載せ替えると全試験が「落ちる」より先に「何も走らない」。
 *  docs/investigation/m2-load-from-disk.logic.md §8)。
 * 相対に'/'を補う案も、根("/")を割り当てる試験の後続のloadがディスクへ
 * 流れて落ちるので採らない(同 §8-4、test/lisp/partition_test.lisp)。
 * 解決できないときホスト共有へ落とす案も、**割り当て名の綴り間違いが
 * ホスト共有の文面で失敗して原因が分からなくなる**ので採らない(同 §9-5)。
 *
 * **作業ディレクトリ(*cwd*)は効かない。** ls/cd/catは効かせているが、
 * loadに効かせると「相対 = ホスト共有」の契約と正面からぶつかる(決定。#195)。
 *
 * open失敗・構文エラー・I/Oエラーのときはos_signal_io_errorで
 * <simple-error>をsignalする(以前は自前で1行表示してg_sym_eval_errorを
 * 返していたが、conditionのメッセージが同じ内容を運ぶため改めた)。
 * ロード中の個々のフォームが打ち切られた場合は理由を表示して続行し、
 * **戻り値はg_sym_tのまま**である(件数を見たい場合はos_load_from_streamを直接呼ぶ)。
 * @param args (path) pathはSTRING(上の契約に従う。先頭が'/'なら絶対、でなければ
 *             ホスト共有のエクスポートルートから見た相対)
 * @param env 評価に使う環境(読み込んだ各S式もこのenvで評価される)
 * @return 最後まで読めればg_sym_t
 */
lisp_val_t cc_load(lisp_val_t args, lisp_val_t env);

/** LOADをglobal_environmentに関数として登録する */
void os_register_load(void);

/* ===================== [#197] 打ち切りを母艦から見えるようにする =====================
 *
 * **loadの意味は変えない。** 上の契約(「打ち切りは失敗にならない」)はそのままで、
 * 変えるのは「母艦から見えるか」だけである。打ち切りの理由は従来
 * proc->stdout_buffer(= 画面)にしか出ず、-display noneで走るQEMU試験の
 * 母艦側からは**何も見えなかった**。結果として「ファイルが半分だけ静かに欠ける」
 * 事故が成果物に痕跡を残さない(docs/investigation/detector-t4-passline.logic.md §4-3)。
 *
 * **Lisp側へ組み込み関数で渡す案は採らない。** native関数を1つ足すと小さいヒープの
 * 試験が固まる罠がある(SMALL_HEAP_SIZEの再調整が必要。documents/pitfalls.md)。
 * 前例に寄せて**Cで数えて直列線へ出す**(kernel.cの9Pの無い起動の要約と同じ形)。
 *
 * 出る行は3種類で、**どれも合否の一行に似せていない**
 * (tools/check_pass_line.pyの在庫に引っかからないようにするため):
 *
 *   [load] abort <名前>: <理由>              打ち切り1件ごと。**なぜ**欠けたか
 *   [load] file <パス>: aborted <件数>       ファイル1本ごと。**どのファイル**か
 *   [load] aborted top-level forms: <総数>   1周の終わりに1回。**0件でも出す**
 *
 * 母艦側の判定はtools/check_load_abort_line.py 1箇所。
 */

/**
 * 診断の1行を書き出す先を差す(既定は0 = どこへも出さない)。
 *
 * **load.cからos_diag_serial_writeを直接呼ばないのは2つの理由からである。**
 *   1. 単体試験(test/c/load_test.c)はinterrupt.cをリンクしない。直接呼ぶと
 *      ダミー実装を足すことになり、**出た行そのものを試験から読めない**
 *   2. 差せる形にしておけば、構文ごとに何が出るかを単体試験で**実測**できる
 *      (#197の完了条件が「読みで埋めない表」を要求している)
 *
 * @param writer 1行(改行込み)を受け取る関数。0なら何も出さない
 */
void os_load_set_diag_writer(void (*writer)(const char *));

/** 打ち切りの総数を0に戻す(1周の頭、または単体試験の各ケースの頭で呼ぶ) */
void os_load_abort_stats_reset(void);

/** これまでに数えた打ち切りの総数(**out_aborted_countを渡さない呼び元のぶんも入る**) */
int os_load_aborted_total(void);

/**
 * 1周の終わりに総数の1行を直列線へ出す。**0件でも必ず出す。**
 *
 * **出ないことを成功と読ませてはいけない。** 行が無ければ母艦側が落ちるようにして
 * ある(#204 / #208で学んだ形。「段がまるごと走らなくても何も出ない」が
 * 最も危ない形である)。
 */
void os_load_report_aborts(void);

#endif /* _LOAD_H_ */
